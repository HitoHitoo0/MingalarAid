CREATE DATABASE IF NOT EXISTS mingalaraid CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE mingalaraid;

CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS assistance_requests (
 id INT AUTO_INCREMENT PRIMARY KEY, reference_id VARCHAR(24) NOT NULL UNIQUE,
 full_name VARCHAR(120) NOT NULL, phone VARCHAR(40) NOT NULL, email VARCHAR(190),
 region VARCHAR(100) NOT NULL, township VARCHAR(100) NOT NULL, address VARCHAR(255) NOT NULL,
 categories TEXT NOT NULL, people_affected INT NOT NULL, urgency VARCHAR(20) NOT NULL,
 description TEXT NOT NULL, contact_method VARCHAR(30), created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS volunteer_applications (
 id INT AUTO_INCREMENT PRIMARY KEY, reference_id VARCHAR(24) NOT NULL UNIQUE,
 full_name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(40) NOT NULL,
 age INT NOT NULL, location VARCHAR(190) NOT NULL, available_days VARCHAR(190) NOT NULL,
 skills TEXT NOT NULL, interests VARCHAR(255) NOT NULL, motivation TEXT NOT NULL,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS demo_donations (
 id INT AUTO_INCREMENT PRIMARY KEY, reference_id VARCHAR(24) NOT NULL UNIQUE,
 donor_name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL, amount INT NOT NULL,
 purpose VARCHAR(80) NOT NULL, payment_status VARCHAR(30) DEFAULT 'DEMO_ONLY',
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS disaster_reports (
 id INT AUTO_INCREMENT PRIMARY KEY, disaster_type VARCHAR(60) NOT NULL,
 title VARCHAR(190) NOT NULL, region VARCHAR(100) NOT NULL,
 published_date VARCHAR(40) NOT NULL, description TEXT NOT NULL,
 is_sample BOOLEAN DEFAULT TRUE
);
